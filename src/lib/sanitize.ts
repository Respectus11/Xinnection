/**
 * Sanitizes plain-text content by stripping HTML tags and control characters.
 * Replaces isomorphic-dompurify / jsdom to ensure seamless compatibility with
 * serverless execution environments (e.g. AWS Lambda / Vercel).
 */
export function sanitizePlainText(input: string): string {
  if (!input) return "";
  return input
    .replace(/<script\b[^<]*(?:(?!<\/script>)<[^<]*)*<\/script>/gi, "")
    .replace(/<style\b[^<]*(?:(?!<\/style>)<[^<]*)*<\/style>/gi, "")
    .replace(/<[^>]+>/g, "")
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/&amp;/g, "&")
    .replace(/&quot;/g, '"')
    .replace(/&#39;/g, "'")
    .trim();
}
